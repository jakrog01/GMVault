import assert from "node:assert/strict"
import { performance } from "node:perf_hooks"
import { createEnvironment } from "../support/obsidian.mjs"

const env = createEnvironment()
const { addFile, app, workspace, modals, opened, byText, buttonComponent } = env
addFile("Active.md", "", { run: "[[Runs/Harbor/Run]]" })
addFile("Runs/Harbor/Run.md", "", { type: "run", campaign: "[[Campaigns/Glass/Campaign]]", party: "[[Parties/Watch/Party]]" })
addFile("Campaigns/Glass/Campaign.md", "", { type: "campaign", system: "dnd5e" })
addFile("Parties/Watch/Party.md", "", { type: "party" })
addFile("Runs/Harbor/State.md", "The [[Campaigns/Glass/NPCs/Aria]] is missing.", { type: "state" })
addFile("Runs/Harbor/Session 2026-10-29.md", "Spoke to [[Campaigns/Glass/NPCs/Aria]].", { type: "session" })
addFile("Runs/Other/Session 2026-10-30.md", "Saw [[Campaigns/Glass/NPCs/Aria]].", { type: "session" })
const aria = addFile("Campaigns/Glass/NPCs/Aria.md", "---\ntype: npc\n---\n# Aria\nA secret.", { type: "npc", aliases: ["The Watcher"] })
addFile("Worlds/Other/NPCs/Aria.md", "", { type: "npc" })
const polish = addFile("Library/dnd5e/Worlds/Coast/Lore/Zaklęcie.md", "A charm.", { type: "lore" })
const city = addFile("Library/dnd5e/Worlds/Coast/Locations/\u0141\u00f3d\u017a.md", "", { type: "location" })
const bram = addFile("Worlds/Other/NPCs/Bram.md", "", { type: "npc" })
addFile("Campaigns/Glass/NPCs/Barbarossa Ram.md", "", { type: "npc" })
for (let n = 0; n < 2000; n++) addFile(`Library/dnd5e/Mechanics/Rules/Rule ${n}.md`, "", { type: "rules" })
const inserted = []
const activeView = new env.MarkdownView()
activeView.editor = { replaceSelection: text => inserted.push(text) }
workspace.activeView = activeView
const TableTools = env.load()
const plugin = new TableTools(app, { id: "table-tools" })
workspace.plugin = plugin
await plugin.onload()
const start = performance.now()
plugin.openLookup()
const lookup = modals.at(-1)
assert.ok(performance.now() - start < 100, "candidate build under 100 ms")
const queryStart = performance.now()
const matches = lookup.query("Aria")
assert.ok(performance.now() - queryStart < 100, "query under 100 ms")
assert.equal(matches[0].candidate.file.path, aria.path)
assert.ok(lookup.query("zaklecie").some(match => match.candidate.file.path === polish.path))
assert.equal(lookup.query("lodz")[0].candidate.file.path, city.path)
assert.equal(lookup.query("bram")[0].candidate.file.path, bram.path, "an exact name beats a scattered match in the active run")
assert.equal(lookup.query("watcher")[0].candidate.file.path, aria.path)
lookup.query("Aria")
lookup.choose()
const card = modals.at(-1)
await new Promise(resolve => setTimeout(resolve, 0))
assert.ok(card.contentEl.textContent.includes("State: The [[Campaigns/Glass/NPCs/Aria]] is missing."))
assert.ok(card.contentEl.textContent.includes("Session 2026-10-29: Spoke to [[Campaigns/Glass/NPCs/Aria]]."))
assert.ok(!card.contentEl.textContent.includes("Runs/Other"))
assert.ok(!card.contentEl.textContent.includes("Saw [["))
byText(card.contentEl, plugin.strings.lookupInsert)[0].click()
assert.deepEqual(inserted, ["[[Aria]]"])
plugin.openLookup()
modals.at(-1).query("Aria")
modals.at(-1).choose()
await new Promise(resolve => setTimeout(resolve, 0))
byText(modals.at(-1).contentEl, plugin.strings.lookupOpen)[0].click()
assert.deepEqual(opened, [aria.path])
plugin.openLookup()
modals.at(-1).query("Aria")
modals.at(-1).choose(0, { ctrlKey: true })
assert.deepEqual(opened, [aria.path, aria.path])
