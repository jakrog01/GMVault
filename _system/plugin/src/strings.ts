export type StringKey = keyof typeof englishStrings;
export type Strings = Record<StringKey, string>;


export function createStrings(override: unknown): Strings {
  const result: Strings = { ...englishStrings };
  if (!override || typeof override !== "object" || Array.isArray(override)) return result;
  for (const key of Object.keys(englishStrings) as StringKey[]) {
    const value = (override as Record<string, unknown>)[key];
    if (typeof value === "string") result[key] = value;
  }
  return result;
}


export function format(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) => key in values ? String(values[key]) : match);
}

const capitalised = (key: string): string => key.charAt(0).toUpperCase() + key.slice(1);

export function conditionLabel(strings: Strings, condition: string): string {
  return strings[`condition${capitalised(condition)}` as StringKey] ?? condition;
}

export function conditionDescription(strings: Strings, condition: string): string {
  return strings[`condition${capitalised(condition)}Description` as StringKey] ?? "";
}
